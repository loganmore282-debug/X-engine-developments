// Drives the built website like a student, against the REAL Shule Notes server code (e2e/mock-server.cjs):
// intro, create account, choose class, home, open a note (the PDF must draw), search in it, profile, desktop layout.
const { chromium } = require('playwright');
const fs = require('fs');
const BASE = process.env.WEB_URL || 'http://localhost:4173';
fs.mkdirSync('e2e-shots', { recursive: true });
(async () => {
  const browser = await chromium.launch();
  const problems = [];
  const shot = async (p, name) => { await p.waitForTimeout(400); await p.screenshot({ path: `e2e-shots/${name}.png` }); };
  const ctx = await browser.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, isMobile: true, hasTouch: true });
  const page = await ctx.newPage();
  page.on('pageerror', (e) => problems.push('page error: ' + e.message));
  const step = (m) => console.log('step:', m);
  step('intro'); await page.goto(BASE + '/');
  await page.waitForSelector('.intro-bottom', { timeout: 15000 }); await shot(page, '01-intro');
  await page.click('text=Continue'); await page.click('text=Continue'); await page.click('text=Get started');
  await page.waitForSelector('text=Welcome back'); await shot(page, '02-sign-in');
  step('register'); await page.click('text=Create an account');
  await page.fill('input[autocomplete=name]', 'Amina Nakato'); await page.fill('input[inputmode=tel]', '0772123456'); await page.fill('input[type=password]', 'study2026');
  await page.click('button:has-text("Create account")');
  await page.waitForSelector('text=Which class are you in?'); await shot(page, '03-choose-class');
  await page.click('button.chip:has-text("Senior 2")'); await page.click('button:has-text("Continue")');
  await page.waitForSelector('.subject-tile'); await shot(page, '04-home');
  // Home does NOT repeat every document under the subject grid (the subjects are the way in); documents show only while searching.
  if ((await page.locator('.note-card').count()) > 0) problems.push('Home repeats the documents under the subject grid');
  await page.fill('input[aria-label="Search notes and exams"]', 'photo');
  await page.waitForSelector('.note-card');
  if ((await page.locator('.subject-grid').count()) > 0) problems.push('the subject grid stays while searching');
  await page.fill('input[aria-label="Search notes and exams"]', 'zzzz-nothing');
  await page.waitForSelector('text=Nothing matches your search');
  await page.fill('input[aria-label="Search notes and exams"]', '');
  await page.waitForSelector('.subject-grid');
  step('open a locked note: the paywall'); await page.fill('input[aria-label="Search notes and exams"]', 'Newton'); await page.click('.note-card:has-text("Newton") >> nth=0');
  await page.waitForSelector('text=Choose a pass'); await shot(page, '04b-paywall');
  await page.click('.plan:has-text("1 day")'); await page.fill('.sheet input[inputmode=tel]', '0772 123 456'); await shot(page, '04c-pass-chosen');
  await page.click('button:has-text("Pay UGX 1,500")'); await page.waitForSelector('text=Check your phone'); await shot(page, '04d-approve');
  await page.waitForSelector('text=Payment received', { timeout: 20000 }); await shot(page, '04e-paid');
  await page.click('button:has-text("Start reading")');
  step('the locked note now opens');
  await page.waitForSelector('.sheet-page canvas', { timeout: 20000 });
  await page.waitForFunction(() => { const c = document.querySelector('.sheet-page canvas'); return c && c.width > 100 && c.style.opacity !== '0'; }, null, { timeout: 20000 });
  await shot(page, '05-reader');
  await page.click('button[aria-label="Search in this document"]'); await page.fill('.drawer input', 'carbon');
  await page.waitForSelector('.hit'); await shot(page, '06-reader-search');
  await page.click('.drawer button[aria-label="Close"]'); await page.click('button[aria-label="Back"]');
  step('profile'); await page.click('.bottom-nav a:has-text("Profile")'); await page.waitForSelector('text=Amina Nakato'); await shot(page, '07-profile');
  for (const row of ['My progress', 'Share Shule Notes', 'Terms of use', 'Privacy policy', 'Help and support']) await page.waitForSelector(`.settings >> text=${row}`, { timeout: 5000 });
  step('progress'); await page.click('.settings >> text=My progress'); await page.waitForSelector('text=this week'); await shot(page, '07b-progress');
  if (await page.locator('.ann-toast').count() > 1) problems.push('more than one announcement toast');
  if (await page.locator('.announce').count()) problems.push('announcement is inside the page again');
  await page.click('button[aria-label="Back"]'); await page.waitForSelector('text=Amina Nakato');
  step('payment history'); await page.click('.settings >> text=Payment history'); await page.waitForSelector('.pay-total'); await page.waitForSelector('.pay-row >> text=Paid'); await shot(page, '07c-payments');
  await page.click('button[aria-label="Back"]'); await page.waitForSelector('text=Amina Nakato');
  await page.click('button[aria-label="Edit name"]'); await page.fill('.sheet input', 'Amina Joy Nakato'); await page.click('.sheet button:has-text("Save")');
  await page.waitForSelector('text=Amina Joy Nakato');
  step('log out'); await page.locator('button.btn:has-text("Log out")').evaluate((el) => el.scrollIntoView({ block: 'center' }));
  await page.click('button.btn:has-text("Log out")'); await page.click('.sheet button:has-text("Log out")'); await page.waitForSelector('text=Welcome back');
  await ctx.close();
  step('desktop'); const d = await browser.newContext({ viewport: { width: 1280, height: 800 } });
  const dp = await d.newPage();
  dp.on('pageerror', (e) => problems.push('desktop page error: ' + e.message));
  await dp.addInitScript(() => localStorage.setItem('shule_intro_seen', '1'));
  await dp.goto(BASE + '/'); await dp.waitForSelector('text=Welcome back'); await shot(dp, '08b-desktop-sign-in');
  await dp.fill('input[inputmode=tel]', '0772123456'); await dp.fill('input[type=password]', 'study2026'); await dp.click('button:has-text("Sign in")');
  await dp.waitForSelector('.subject-tile'); await shot(dp, '08-desktop-home');
  // Subjects are a grid; a tap opens that subject's own page (its documents first), and Back returns to Home.
  if ((await dp.locator('.subject-grid .subject-tile').count()) < 2) problems.push('the subject grid has fewer than 2 tiles');
  await dp.click('.subject-tile >> nth=0'); await dp.waitForSelector('.subject-hero'); await dp.waitForSelector('.subject-hero ~ .grid .note-card, .subject-hero ~ .empty');
  if (!/\/subject\//.test(dp.url())) problems.push('a subject tile did not open its own page');
  await shot(dp, '08c-desktop-subject');
  await dp.click('.subject-hero .back-btn'); await dp.waitForSelector('.subject-grid');
  if (/\/subject\//.test(dp.url())) problems.push('Back from a subject page stayed on it');
  await dp.click('.subject-tile >> nth=0'); await dp.waitForSelector('.subject-hero ~ .grid .note-card'); await dp.click('.note-card >> nth=0'); await dp.waitForSelector('.sheet-page canvas', { timeout: 20000 }); await dp.waitForTimeout(1200); await shot(dp, '08d-desktop-reader');
  await dp.keyboard.press('ArrowRight'); await dp.waitForFunction(() => /Page 2 of/.test(document.querySelector('.reader-top')?.textContent || ''), null, { timeout: 8000 });
  await dp.keyboard.press('/'); await dp.waitForSelector('.drawer input'); await dp.keyboard.press('Escape'); await dp.waitForSelector('.drawer', { state: 'detached' });
  await dp.click('button[aria-label="Search in this document"]'); await dp.fill('.drawer input', 'carbon'); await dp.waitForSelector('.hit'); await dp.waitForTimeout(500); await shot(dp, '08e-desktop-reader-search');
  await dp.click('.drawer button[aria-label="Close"]'); await dp.click('button[aria-label="Back"]');
  await dp.click('.nav-links a:has-text("Profile")'); await dp.waitForSelector('text=Amina'); await shot(dp, '08f-desktop-profile');
  await browser.close();
  if (problems.length) { console.error(problems.join('\n')); process.exit(1); }
  console.log('the website works end to end');
})().catch((e) => { console.error('FAILED:', e.message.split('\n')[0]); process.exit(1); });
